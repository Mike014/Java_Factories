package Esercizio1;

public class StampaSequenza {
    public static void main(String[] args)
    {

        System.out.println("println: Primo");
        System.out.println("println: Secondo");
        System.out.println("println: Terzo");

        System.out.print("print: Primo");
        System.out.print("print: Secondo");
        System.out.print("print: Terzo");

        System.out.print("Primo\n");
        System.out.print("Secondo\n");
        System.out.print("Terzo\n");

    }
}
